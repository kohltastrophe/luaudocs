describe("the derived navbar", () => {
	it("marks a section entry current across the section, a single page only on it", () => {
		const { dir, docsDir } = project();
		mkdirSync(join(docsDir, "guide"), { recursive: true });
		writeFileSync(join(docsDir, "guide", "intro.md"), "# Intro\n");
		writeFileSync(join(dir, "CHANGELOG.md"), "# Changelog\n");
		sync(dir, API_SIDEBAR);
		const baked = readFileSync(join(docsDir, ".vitepress", "config.mts"), "utf8");
		expect(baked).toContain('"activeMatch": "^/guide/"');
		expect(baked).toContain('"activeMatch": "^/api/"');
		// the changelog is one page, so its link is the whole of its match
		expect(baked).toMatch(/"text": "Changelog",\n\t+"link": "\/changelog"\n/);
	});
});

describe("[site] siteTitle", () => {
	it("bakes the navbar override, false included", () => {
		const dir = tempDir();
		mkdirSync(join(dir, "src"));
		const config = join(dir, "luaudocs.toml");
		const baked = join(dir, ".luaudocs", ".vitepress", "config.mts");
		writeFileSync(config, 'title = "X"\n\n[site]\nsiteTitle = "Short"\n');
		syncSite(createContext(dir), { guides: [], apiSidebar: [] });
		expect(readFileSync(baked, "utf8")).toContain('siteTitle: "Short",');

		writeFileSync(config, 'title = "X"\n\n[site]\nsiteTitle = false\n');
		syncSite(createContext(dir), { guides: [], apiSidebar: [] });
		expect(readFileSync(baked, "utf8")).toContain("siteTitle: false,");
	});
});

describe("the generated changelog page", () => {
	it("mirrors CHANGELOG.md while it exists, and removes only its own copy", () => {
		const { dir, docsDir } = project();
		writeFileSync(join(dir, "CHANGELOG.md"), "# Changelog\n\n- first\n");
		sync(dir);
		const target = join(docsDir, "changelog.md");
		// the generated frontmatter doubles as the ownership marker here
		const written = readFileSync(target, "utf8");
		expect(written.startsWith('---\ntitle: "Changelog"')).toBe(true);
		expect(written).toContain("- first");

		// the source is gone: the generated copy must not keep publishing it
		rmSync(join(dir, "CHANGELOG.md"));
		sync(dir);
		expect(existsSync(target)).toBe(false);

		// a user-owned changelog.md (no marker) is never the build's to delete
		writeFileSync(target, "# Mine\n");
		sync(dir);
		expect(readFileSync(target, "utf8")).toBe("# Mine\n");
	});
});

describe("build --url", () => {
	it("overrides [docs] url and reaches the baked site config", () => {
		const dir = tempDir();
		mkdirSync(join(dir, "src"));
		writeFileSync(
			join(dir, "luaudocs.toml"),
			'title = "X"\n\n[docs]\nurl = "https://old.example.com"\n',
		);
		const context = createContext(dir, { url: "https://user.github.io/repo/" });
		expect(context.config.docs.url).toBe("https://user.github.io/repo");
		syncSite(context, { guides: [], apiSidebar: [] });
		const baked = readFileSync(join(dir, ".luaudocs", ".vitepress", "config.mts"), "utf8");
		expect(baked).toContain('base: "/repo/"');
		expect(baked).toContain("https://user.github.io/repo");
		expect(baked).not.toContain("old.example.com");
	});
});

describe("page trails", () => {
	/** The guide tree as it reaches the trail builder, from files on disk. */
	function guidesOf(files: Record<string, string>): GuideItem[] {
		const dir = tempDir();
		for (const [rel, text] of Object.entries(files)) {
			const abs = join(dir, ".luaudocs", "guide", rel);
			mkdirSync(dirname(abs), { recursive: true });
			writeFileSync(abs, text);
		}
		return collectGuides(join(dir, ".luaudocs"));
	}

	const HOME = { text: "Home", link: "/" };

	it("hangs a guide page off Home, its folders between", () => {
		const guides = guidesOf({
			"getting-started.md": "# Getting Started\n",
			"reference/tags.md": "# Tags\n",
		});
		const trails = pageTrails(guides, undefined, false);
		expect(trails["guide/getting-started.md"]).toEqual([HOME]);
		// no reference/index.md, so the folder is a label with nowhere to go
		expect(trails["guide/reference/tags.md"]).toEqual([HOME, { text: "Reference" }]);
	});

	it("links a folder to its own index page, which never trails itself", () => {
		const guides = guidesOf({
			"reference/index.md": "# Reference\n",
			"reference/tags.md": "# Tags\n",
		});
		const trails = pageTrails(guides, undefined, false);
		expect(trails["guide/reference/tags.md"]).toEqual([
			HOME,
			{ text: "Reference", link: "/guide/reference/" },
		]);
		expect(trails["guide/reference/index.md"]).toEqual([HOME]);
	});

	it("puts Home above the API trails the emitter derived", () => {
		const api = new Map([
			// the emitter's own map: the index page included, trailed by nothing
			["index.md", []],
			["Flux.md", [{ text: "Overview", link: "/api/" }]],
			[
				"Queue.md",
				[
					{ text: "Overview", link: "/api/" },
					{ text: "Flux", link: "/api/Flux" },
				],
			],
		]);
		const trails = pageTrails([], api, true);
		expect(trails["api/Queue.md"]).toEqual([
			HOME,
			{ text: "Overview", link: "/api/" },
			{ text: "Flux", link: "/api/Flux" },
		]);
		// the API index is the section's root, and the changelog a page beside it
		expect(trails["api/index.md"]).toEqual([HOME]);
		expect(trails["changelog.md"]).toEqual([HOME]);
	});

	it("leaves out what the site does not publish", () => {
		const trails = pageTrails([], new Map(), false);
		// no pages emitted, so no /api/ index exists to trail; no changelog either
		expect(trails).toEqual({});
	});

	it("bakes the map the render-time rule reads", () => {
		const { dir, docsDir } = project();
		mkdirSync(join(docsDir, "guide"), { recursive: true });
		writeFileSync(join(docsDir, "guide", "usage.md"), "# Usage\n");
		sync(dir, API_SIDEBAR);
		const baked = readFileSync(join(docsDir, ".vitepress", "generated", "trails.ts"), "utf8");
		expect(baked).toContain("export const pageTrails");
		expect(baked).toContain('"guide/usage.md"');
		const config = readFileSync(join(docsDir, ".vitepress", "config.mts"), "utf8");
		expect(config).toContain('from "./generated/trails.ts"');
		expect(config).toContain("installMarkupRule(md, pageTrails)");
	});
});

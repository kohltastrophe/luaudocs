/**
 * Tests for docs-root file generation, README link rewriting, guide sidebars,
 * and breadcrumb trails (`src/site.ts`).
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { createContext } from "../src/build";
import type { SidebarItem } from "../src/nav";
import { isGeneratedFile } from "../src/pages";
import { collectGuides, pageTrails, syncSite, type GuideItem } from "../src/site";
import { makeTempDirFactory } from "./helpers";

const tempDir = makeTempDirFactory("luaudocs-site-");

function project(toml?: string): { dir: string; docsDir: string } {
	const dir = tempDir();
	mkdirSync(join(dir, "src"));
	if (toml !== undefined) {
		writeFileSync(join(dir, "luaudocs.toml"), toml);
	}
	return { dir, docsDir: join(dir, ".luaudocs") };
}

const REPO_TOML = 'title = "X"\n\n[repo]\nurl = "https://github.com/you/repo"\n';
const API_SIDEBAR: SidebarItem[] = [{ text: "Overview", link: "/api/" }];

function sync(dir: string, apiSidebar: SidebarItem[] = []): string[] {
	const context = createContext(dir);
	return syncSite(context, { guides: collectGuides(context.docsDir), apiSidebar });
}

function writeGuides(docsDir: string, files: Record<string, string>): void {
	for (const [rel, text] of Object.entries(files)) {
		const abs = join(docsDir, "guide", rel);
		mkdirSync(dirname(abs), { recursive: true });
		writeFileSync(abs, text);
	}
}

function guidesOf(files: Record<string, string>): GuideItem[] {
	const docsDir = join(tempDir(), ".luaudocs");
	writeGuides(docsDir, files);
	return collectGuides(docsDir);
}

describe("generated landing page, .gitignore, and changelog", () => {
	it("generates hero or README landing pages, respects marker ownership, and manages .gitignore", () => {
		const { dir, docsDir } = project();
		sync(dir, API_SIDEBAR);
		let index = readFileSync(join(docsDir, "index.md"), "utf8");
		expect(index).toContain("# Generated by luaudocs");
		expect(index).toContain("layout: home");
		expect(index).toContain(`name: ${JSON.stringify(basename(dir))}`);
		expect(index).toContain("link: /api/");
		expect(index).not.toContain("Get Started");

		const ignorePath = join(docsDir, ".gitignore");
		const ignore = readFileSync(ignorePath, "utf8");
		for (const line of [
			".vitepress/",
			"api/",
			"package.json",
			"node_modules/",
			"index.md",
			".gitignore",
		]) {
			expect(ignore, line).toContain(line);
		}
		writeFileSync(ignorePath, "# mine\n");

		// When no API pages emit and a guide exists, hero links to guide and omits /api/
		writeGuides(docsDir, { "intro.md": "# Intro\n" });
		sync(dir);
		index = readFileSync(join(docsDir, "index.md"), "utf8");
		expect(index).not.toContain("link: /api/");
		expect(index).toContain("text: Get Started");
		expect(index).toContain("link: /guide/intro");
		expect(readFileSync(join(docsDir, ".vitepress", "config.mts"), "utf8")).not.toContain(
			'"link": "/api/"',
		);
		expect(readFileSync(ignorePath, "utf8")).toBe("# mine\n");

		// Marked index.md is replaced by README when README appears (honoring hide markers)
		writeFileSync(
			join(dir, "README.md"),
			"badges\n<!--moonwave-hide-before-this-line-->\n# Lib\nprose\n<!--moonwave-hide-after-this-line-->\nfooter\n",
		);
		sync(dir);
		index = readFileSync(join(docsDir, "index.md"), "utf8");
		expect(index).toContain("# Generated by luaudocs");
		expect(index).toContain("# Lib\nprose");
		expect(index).not.toContain("badges");
		expect(index).not.toContain("footer");

		// Unmarked index.md is user-owned and never overwritten (nor ignored in a fresh .gitignore)
		const userOwned = project();
		writeFileSync(join(userOwned.dir, "README.md"), "[contrib](CONTRIBUTING.md)\n");
		mkdirSync(userOwned.docsDir, { recursive: true });
		writeFileSync(join(userOwned.docsDir, "index.md"), "# Mine\n");
		expect(sync(userOwned.dir)).toEqual([]);
		expect(readFileSync(join(userOwned.docsDir, "index.md"), "utf8")).toBe("# Mine\n");
		expect(readFileSync(join(userOwned.docsDir, ".gitignore"), "utf8")).not.toMatch(
			/^index\.md$/m,
		);
	});

	it("rewrites README links through [repo], public/, and site base, and warns on unreachable links", () => {
		const { dir, docsDir } = project(REPO_TOML);
		mkdirSync(join(docsDir, "public"), { recursive: true });
		writeFileSync(join(docsDir, "public", "copied.svg"), "<svg />");
		writeFileSync(
			join(dir, "README.md"),
			[
				"[contrib](CONTRIBUTING.md) [license](./LICENSE.txt#terms)",
				"![shot](media/shot.png) [that shot](media/shot.png)",
				"[angled](<CONTRIBUTING.md>)",
				"[guide](.luaudocs/guide/intro.md) [asset](.luaudocs/public/logo.svg)",
				'<img src=".moonwave/static/copied.svg" /> <img src=".moonwave/static/uncopied.svg" />',
				"![badge][build] [the file][doc]",
				"see `CONTRIBUTING.md` and `.moonwave/static/copied.svg`",
				"[build]: media/badge.svg",
				"[doc]: CONTRIBUTING.md",
				"[site](https://example.com) [top](#usage)",
			].join("\n\n") + "\n",
		);
		expect(sync(dir)).toEqual([]);
		const index = readFileSync(join(docsDir, "index.md"), "utf8");
		expect(index).toContain("(https://github.com/you/repo/blob/main/CONTRIBUTING.md)");
		expect(index).toContain("(https://github.com/you/repo/blob/main/LICENSE.txt#terms)");
		expect(index).toContain("![shot](https://github.com/you/repo/raw/main/media/shot.png)");
		expect(index).toContain(
			"[that shot](https://github.com/you/repo/blob/main/media/shot.png)",
		);
		expect(index).toContain(
			"[angled](<https://github.com/you/repo/blob/main/CONTRIBUTING.md>)",
		);
		expect(index).toContain("(/guide/intro)");
		expect(index).toContain("(/logo.svg)");
		expect(index).toContain('src="/copied.svg"');
		expect(index).toContain(
			'src="https://github.com/you/repo/raw/main/.moonwave/static/uncopied.svg"',
		);
		expect(index).toContain("[build]: https://github.com/you/repo/raw/main/media/badge.svg");
		expect(index).toContain("[doc]: https://github.com/you/repo/blob/main/CONTRIBUTING.md");
		expect(index).toContain("`CONTRIBUTING.md` and `.moonwave/static/copied.svg`");
		expect(index).toContain("(https://example.com)");
		expect(index).toContain("(#usage)");

		// Site base applies only to raw HTML hrefs
		const based = project('title = "X"\n\n[docs]\nurl = "https://you.github.io/repo"\n');
		mkdirSync(join(based.docsDir, "public"), { recursive: true });
		writeFileSync(join(based.docsDir, "public", "logo.svg"), "<svg />");
		writeFileSync(
			join(based.dir, "README.md"),
			'<img src=".moonwave/static/logo.svg" />\n\n![shot](.luaudocs/public/shot.png)\n\n' +
				'[guide](.luaudocs/guide/intro.md)\n\n<a href=".luaudocs/guide/intro.md">g</a>\n',
		);
		expect(sync(based.dir)).toEqual([]);
		const basedIndex = readFileSync(join(based.docsDir, "index.md"), "utf8");
		expect(basedIndex).toContain('src="/logo.svg"');
		expect(basedIndex).toContain("(/shot.png)");
		expect(basedIndex).toContain("(/guide/intro)");
		expect(basedIndex).toContain('href="/repo/guide/intro"');

		// Warnings when [repo] is absent or a link climbs above repo root
		const noRepo = project();
		writeFileSync(
			join(noRepo.dir, "README.md"),
			"[contrib](CONTRIBUTING.md)\n\n[again](CONTRIBUTING.md) [license](LICENSE.txt)\n",
		);
		expect(sync(noRepo.dir)).toEqual([
			"warning: README.md links CONTRIBUTING.md, LICENSE.txt, which the generated " +
				"site does not serve; set [repo] to point them at the repository",
		]);
		expect(readFileSync(join(noRepo.docsDir, "index.md"), "utf8")).toContain(
			"(CONTRIBUTING.md)",
		);

		const climb = project(REPO_TOML);
		writeFileSync(join(climb.dir, "README.md"), "[shared](../shared/README.md)\n");
		expect(sync(climb.dir)).toEqual([
			"warning: README.md links ../shared/README.md, which the generated " +
				"site does not serve and [repo] cannot reach",
		]);
	});

	it("mirrors CHANGELOG.md and removes only tool-owned copies across LF, CRLF, and legacy frontmatter", () => {
		const { dir, docsDir } = project();
		const target = join(docsDir, "changelog.md");
		writeFileSync(join(dir, "CHANGELOG.md"), "# Changelog\n\n- first\n");
		sync(dir);
		const written = readFileSync(target, "utf8");
		expect(isGeneratedFile(written)).toBe(true);
		expect(written).toContain('title: "Changelog"');
		expect(written).toContain("- first");

		// CRLF checkout of generated copy still recognized and removed when CHANGELOG.md is gone
		writeFileSync(target, written.replace(/\n/g, "\r\n"));
		rmSync(join(dir, "CHANGELOG.md"));
		sync(dir);
		expect(existsSync(target)).toBe(false);

		// Legacy frontmatter (pre-marker) recognized in both LF and CRLF
		for (const eol of ["\n", "\r\n"]) {
			writeFileSync(
				target,
				[
					"---",
					'title: "Changelog"',
					"editLink: false",
					"lastUpdated: false",
					"---",
					"",
					"# Changelog",
					"",
				].join(eol),
			);
			sync(dir);
			expect(existsSync(target)).toBe(false);
		}

		// User-owned changelog.md is preserved
		writeFileSync(target, "# Mine\n");
		sync(dir);
		expect(readFileSync(target, "utf8")).toBe("# Mine\n");
	});
});

describe("baked VitePress config and navigation", () => {
	it("bakes head, ogImage, siteTitle, derived navbar, root-relative editLink, and --url override", () => {
		const { dir, docsDir } = project(
			[
				'title = "X"',
				"[repo]",
				'url = "https://github.com/you/repo"',
				"[docs]",
				'dir = "./site/"',
				'url = "https://old.example.com"',
				"[site]",
				'siteTitle = "Short"',
				'ogImage = "/og.png"',
				"[[site.head]]",
				'tag = "script"',
				'attrs = { defer = "true", src = "https://plausible.io/js/script.js", "data-domain" = "docs.example.com" }',
				"[[site.head]]",
				'tag = "script"',
				'content = "track()"',
			].join("\n"),
		);
		void docsDir;
		const siteDir = join(dir, "site");
		writeGuides(siteDir, { "intro.md": "# Intro\n" });
		writeFileSync(join(dir, "CHANGELOG.md"), "# Changelog\n");

		const context = createContext(dir, { url: "https://user.github.io/repo/" });
		expect(context.config.docs.url).toBe("https://user.github.io/repo");
		syncSite(context, { guides: collectGuides(siteDir), apiSidebar: API_SIDEBAR });

		const bakedPath = join(siteDir, ".vitepress", "config.mts");
		const baked = readFileSync(bakedPath, "utf8");
		expect(baked).toContain('siteTitle: "Short",');
		expect(baked).toContain('"og:image"');
		expect(baked).toContain("https://user.github.io/repo/og.png");
		expect(baked).toContain("summary_large_image");
		expect(baked).toContain('"data-domain": "docs.example.com"');
		expect(baked).toContain('"track()"');
		expect(baked.indexOf("og:site_name")).toBeLessThan(baked.indexOf("data-domain"));
		expect(baked).toContain('"activeMatch": "^/guide/"');
		expect(baked).toContain('"activeMatch": "^/api/"');
		expect(baked).toMatch(/"text": "Changelog",\n\t+"link": "\/changelog"\n/);
		expect(baked).toContain('pattern: "https://github.com/you/repo/edit/main/site/:path"');
		expect(baked).toContain('base: "/repo/"');
		expect(baked).not.toContain("old.example.com");

		// siteTitle = false and absolute docs.dir
		writeFileSync(
			join(dir, "luaudocs.toml"),
			`${REPO_TOML}\n[docs]\ndir = ${JSON.stringify(siteDir)}\n[site]\nsiteTitle = false\n`,
		);
		syncSite(createContext(dir), { guides: [], apiSidebar: [] });
		const bakedFalse = readFileSync(bakedPath, "utf8");
		expect(bakedFalse).toContain("siteTitle: false,");
		expect(bakedFalse).toContain('pattern: "https://github.com/you/repo/edit/main/site/:path"');
	});

	it("preserves API navigation while rebaking guides on an error build", () => {
		const { dir, docsDir } = project();
		const generated = join(docsDir, ".vitepress", "generated");
		syncSite(createContext(dir), { guides: [], apiSidebar: undefined });
		expect(readFileSync(join(generated, "api-nav.ts"), "utf8")).toContain(
			"apiSidebar: DefaultTheme.SidebarItem[] = [];",
		);

		writeGuides(docsDir, { "usage.md": "# Usage\n" });
		const context = createContext(dir);
		syncSite(context, {
			guides: collectGuides(docsDir),
			apiSidebar: [
				{ text: "Overview", link: "/api/" },
				{ text: "Kept", link: "/api/Kept" },
			],
			apiTrails: new Map([["Kept.md", [{ text: "Overview", link: "/api/" }]]]),
		});
		const apiNav = readFileSync(join(generated, "api-nav.ts"), "utf8");
		expect(apiNav).toContain('"/api/Kept"');

		writeGuides(docsDir, { "added.md": "# Added\n" });
		syncSite(context, {
			guides: collectGuides(docsDir),
			apiSidebar: undefined,
			hasErrors: true,
		});
		expect(readFileSync(join(generated, "api-nav.ts"), "utf8")).toBe(apiNav);
		expect(readFileSync(join(generated, "sidebar.ts"), "utf8")).toContain('"/guide/added"');
		expect(readFileSync(join(generated, "trails.ts"), "utf8")).toContain('"guide/added.md"');
	});
});

describe("guides sidebar and page trails", () => {
	const page = (title: string, ...keys: string[]): string =>
		["---", `title: ${title}`, ...keys, "---", "", `The ${title} page.`, ""].join("\n");

	const outline = (items: GuideItem[]): string[] =>
		items.map((item) =>
			item.items ? `${item.text} [${outline(item.items).join(", ")}]` : item.text,
		);

	function bakedSidebar(files: Record<string, string>): string {
		const { dir, docsDir } = project();
		writeGuides(docsDir, files);
		sync(dir, API_SIDEBAR);
		return readFileSync(join(docsDir, ".vitepress", "generated", "sidebar.ts"), "utf8");
	}

	it("orders siblings, leads groups with index.md, reads JSON/YAML sidecars, and excludes _ prefixes", () => {
		expect(
			outline(
				guidesOf({
					"index.md": page("RootOverview", "sidebar_position: 9"),
					"intro.md": page("Intro", "sidebar_position: 1"),
					"deploying.md": page("Deploying", "sidebar_position: 3"),
					"reference/index.md": page("Overview", "sidebar_position: 2"),
					"reference/aardvark.md": page("Aardvark", "sidebar_position: 0"),
					"reference/cli.md": page("CLI", "sidebar_position: 1"),
					"extras/one.md": page("One", "sidebar_position: 1"),
					"zzz.md": page("Later"),
					"_partial.md": page("Partial"),
					"_drafts/one.md": page("One"),
					"reference/_wip/two.md": page("Two"),
				}),
			),
		).toEqual([
			"RootOverview",
			"Intro",
			"Reference [Overview, Aardvark, CLI]",
			"Deploying",
			"Extras [One]",
			"Later",
		]);

		// Fractional/negative/non-numeric positions and sidecar vs page key separation
		expect(
			outline(
				guidesOf({
					"two.md": page("Two", "sidebar_position: 2"),
					"three.md": page("Three", "sidebar_position: 3"),
					"between/_category_.json": '{ "label": "Mid", "position": 2.5 }\n',
					"between/one.md": page("One"),
					"first/_category_.json": '{ "position": -1 }\n',
					"first/one.md": page("One"),
					"nowhere/_category_.json": '{ "position": "high", "sidebar_position": 1 }\n',
					"nowhere/one.md": page("One"),
					"own/index.md": page("Overview", "position: 1"),
					"own/one.md": page("One"),
				}),
			),
		).toEqual([
			"First [One]",
			"Two",
			"Mid [One]",
			"Three",
			"Nowhere [One]",
			"Own [Overview, One]",
		]);

		// Sidecar outranking index.md + YAML sidecars (blank key, True/False booleans) + invalid JSON
		const yamlGuides = guidesOf({
			"reference/_category_.json": '{ "position": 1 }\n',
			"reference/index.md": page("Overview", "sidebar_position: 9", "collapsed: true"),
			"reference/cli.md": page("CLI"),
			"yml/_category_.yml": "label:\nposition: 2\ncollapsed: True\n",
			"yml/one.md": page("One"),
			"fixed/_category_.yml": "label: Fixed Guide\nposition: 3\ncollapsible: False\n",
			"fixed/one.md": page("One"),
		});
		expect(outline(yamlGuides)).toEqual([
			"Reference [Overview, CLI]",
			"Yml [One]",
			"Fixed Guide [One]",
		]);
		expect(yamlGuides.map((g) => [g.collapsed, g.collapsible])).toEqual([
			[true, undefined],
			[true, undefined],
			[undefined, false],
		]);

		expect(() =>
			guidesOf({
				"reference/_category_.json": '{ "label": "Reference", }\n',
				"reference/cli.md": page("CLI"),
			}),
		).toThrow(/_category_\.json/);
	});

	it("bakes top-level Guide wrapper vs folder sections and group collapsed states", () => {
		const wrapped = bakedSidebar({
			"intro.md": page("Intro"),
			"closed/_category_.json": '{ "collapsed": true }\n',
			"closed/one.md": page("One"),
			"asked/index.md": page("Overview", "collapsed: true"),
			"asked/one.md": page("One"),
			"fixed/_category_.json": '{ "collapsible": false }\n',
			"fixed/one.md": page("One"),
			"bare/one.md": page("One"),
		});
		expect(wrapped).toMatch(/guideSidebar[^]*"text": "Guide",\n\t+"items"/);
		expect(wrapped).toMatch(/"text": "Closed",\n\t+"collapsed": true/);
		expect(wrapped).toMatch(/"text": "Asked",\n\t+"collapsed": true/);
		expect(wrapped).toMatch(/"text": "Fixed",\n\t+"items"/);
		expect(wrapped).toMatch(/"text": "Bare",\n\t+"collapsed": false/);

		const folderSections = bakedSidebar({
			"bare/one.md": page("One"),
			"closed/_category_.json": '{ "collapsed": true }\n',
			"closed/one.md": page("One"),
			"open/_category_.json": '{ "collapsible": true }\n',
			"open/one.md": page("One"),
		});
		expect(folderSections).not.toContain('"text": "Guide"');
		expect(folderSections).toMatch(/"text": "Bare",\n\t+"items"/);
		expect(folderSections).toMatch(/"text": "Closed",\n\t+"collapsed": true/);
		expect(folderSections).toMatch(/"text": "Open",\n\t+"collapsed": false/);
	});

	it("builds and bakes page trails for guides, API pages, and changelog", () => {
		const HOME = { text: "Home", link: "/" };
		const guides = guidesOf({
			"getting-started.md": "# Getting Started\n",
			"unindexed/tags.md": "# Tags\n",
			"reference/index.md": "# Reference\n",
			"reference/cli.md": "# CLI\n",
		});
		const api = new Map([
			["index.md", []],
			["Flux.md", [{ text: "Overview", link: "/api/" }]],
			[
				"Queue.md",
				[
					{ text: "Overview", link: "/api/" },
					{ text: "Flux", link: "/api/Flux" },
				],
			],
		]);
		const trails = pageTrails(guides, api, true);
		expect(trails["guide/getting-started.md"]).toEqual([HOME]);
		expect(trails["guide/unindexed/tags.md"]).toEqual([HOME, { text: "Unindexed" }]);
		expect(trails["guide/reference/cli.md"]).toEqual([
			HOME,
			{ text: "Reference", link: "/guide/reference/" },
		]);
		expect(trails["guide/reference/index.md"]).toEqual([HOME]);
		expect(trails["api/Queue.md"]).toEqual([
			HOME,
			{ text: "Overview", link: "/api/" },
			{ text: "Flux", link: "/api/Flux" },
		]);
		expect(trails["api/index.md"]).toEqual([HOME]);
		expect(trails["changelog.md"]).toEqual([HOME]);
		expect(pageTrails([], new Map(), false)).toEqual({});
	});
});

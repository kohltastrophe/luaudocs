async function initCapturing(options: Parameters<typeof initProject>[0]): Promise<string[]> {
	const lines: string[] = [];
	const spy = vi
		.spyOn(console, "log")
		.mockImplementation((...args: unknown[]) => void lines.push(args.join(" ")));
	try {
		await initProject(options);
	} finally {
		spy.mockRestore();
		vi.spyOn(console, "log").mockImplementation(() => {});
	}
	return lines;
}

async function runInit(
	files: Record<string, string | Buffer> = {},
	opts: Omit<Parameters<typeof initProject>[0], "targetDir"> = {},
): Promise<{ dir: string; docsDir: string; lines: string[] }> {
	const dir = tempDir();
	for (const [rel, content] of Object.entries(files)) {
		const abs = join(dir, rel);
		mkdirSync(dirname(abs), { recursive: true });
		writeFileSync(abs, content);
	}
	const lines = await initCapturing({ targetDir: dir, ...opts });
	return { dir, docsDir: join(dir, ".luaudocs"), lines };
}


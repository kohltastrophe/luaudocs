			"[Yields] [Server] [Plugin] Blocks until the widget is saved.",
			"[Deprecated since v2: use [Tagged.create] instead] [since v0.9.0]",
			"): [Deprecated] [Unreleased]\n",
			"[Read Only] The registry stops accepting widgets",
